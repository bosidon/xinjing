(async () => {
    await database.connect();
    
    let updated = 0;
    for (const [orderIndex, newText] of enrichedQuestions) {
        const existing = await database.get(
            'SELECT id, question_text FROM questions WHERE assessment_id = 8 AND order_index = ?',
            [orderIndex]
        );
        if (existing) {
            if (existing.question_text.length < 30 || !existing.question_text.includes('—')) {
                await database.run(
                    'UPDATE questions SET question_text = ? WHERE id = ?',
                    [newText, existing.id]
                );
                console.log(`✅ 更新题${orderIndex}: ${existing.question_text.slice(0,30)}... → ${newText.slice(0,40)}...`);
                updated++;
            } else {
                console.log(`⏭️ 题${orderIndex} 已有完整描述，跳过`);
            }
        } else {
            console.log(`❌ 未找到题${orderIndex}，跳过`);
        }
    }
    
    console.log(`\n更新完成：共修改 ${updated} 题`);
    process.exit(0);
})().catch(e => {
    console.error('失败:', e.message);
    process.exit(1);
});
